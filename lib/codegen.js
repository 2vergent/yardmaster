// Generate nginx.conf and yardmaster.code-workspace from services.yaml.
//
// Both outputs are local-only (gitignored) — services.yaml is the
// committed source of truth, and these get rewritten by `ym regen`,
// `ym setup`, and `ym up` from whatever active stack the developer is on.

import fs from "fs";
import path from "path";
import { YM_ROOT, YM_LOCAL } from "./bootstrap.js";
import { loadServices, gatewayPort } from "./services.js";
import { activeServiceNames } from "./presets.js";
import * as state from "./state.js";

const NGINX_CONF = path.join(YM_LOCAL, "nginx.conf");
const WORKSPACE = path.join(YM_ROOT, "yardmaster.code-workspace");

// What counts as "active" for codegen purposes: only what's in the active
// selection (preset / built-in stack / user stack / custom). The selection
// is authoritative — `ym add` plumbs into it, `ym remove` takes things out,
// `ym stack apply` replaces it. Leftover clones from a previous stack stay
// on disk but DON'T pollute nginx routes or the VS Code workspace; bring
// them back into the selection with `ym add <name>` when wanted.
function isActiveForCodegen(svc) {
  return new Set(activeServiceNames()).has(svc.name);
}

function activeServices() {
  return loadServices().services.filter(isActiveForCodegen);
}

const header = (port) => `# =============================================================================
# AUTO-GENERATED by ym from services.yaml — DO NOT EDIT BY HAND.
# Regenerate with:  ym regen
# =============================================================================

worker_processes  1;

events {
    worker_connections  1024;
}

http {
    client_max_body_size 50m;
    default_type  application/octet-stream;

    sendfile        on;
    keepalive_timeout  65;

    server {
        listen ${port};
        server_name localhost;
`;

const FOOTER = `    }
}
`;

export function generateNginxConf() {
  const services = activeServices()
    .filter((s) => s.routes && s.routes.length > 0)
    .sort((a, b) => a.name.localeCompare(b.name));

  // Nginx uses longest-prefix match for `location /x` automatically — the
  // order in this file does not affect routing. Services are listed
  // alphabetically purely for human readability of the generated file.
  let body = "\n";
  for (const svc of services) {
    const routes = [...svc.routes].sort();
    for (const route of routes) {
      body += `        location ${route} {\n`;
      body += `            proxy_pass http://localhost:${svc.port};\n`;
      body += `            proxy_set_header Host $host;\n`;
      body += `            proxy_set_header X-Real-IP $remote_addr;\n`;
      body += `        }\n\n`;
    }
  }

  return header(gatewayPort()) + body + FOOTER;
}

export function writeNginxConf() {
  const content = generateNginxConf();
  fs.writeFileSync(NGINX_CONF, content, "utf8");
  return NGINX_CONF;
}

// ---- VS Code multi-root workspace ----------------------------------------

export function generateVSCodeWorkspace() {
  // Every CLONED service repo on disk — NOT just the active selection. The
  // workspace should mirror what you physically have so its Source Control
  // panel shows every repo's changes, and so it stops churning as you
  // ym add/remove from the running stack. (nginx codegen still uses the
  // active selection — only this view is disk-based.)
  const cloned = loadServices().services
    .filter((s) => fs.existsSync(path.join(YM_ROOT, s.name)))
    .sort((a, b) => a.name.localeCompare(b.name));

  const folders = cloned.map((s) => ({ name: s.name, path: s.name }));

  // Plus any extra folders the dev added via `ym workspace add` — non-service
  // repos kept inside the workspace, or projects elsewhere on disk. Persisted in
  // .ym/state.json, so they survive every regen. Folders inside the workspace get
  // a relative path (like the services); anything outside stays absolute.
  for (const p of state.getWorkspaceExtra()) {
    const abs = path.resolve(p);
    if (folders.some((f) => path.resolve(YM_ROOT, f.path) === abs)) continue;
    const rel = path.relative(YM_ROOT, abs);
    const inside = rel && !rel.startsWith("..") && !path.isAbsolute(rel);
    folders.push({ name: path.basename(abs), path: inside ? rel : abs });
  }

  return {
    folders,
    settings: {
      "files.exclude": {
        "**/.git": true,
        "**/node_modules": true,
      },
      "search.exclude": {
        "**/node_modules": true,
        "**/dist": true,
      },
      "git.detectSubmodulesLimit": 30,
    },
    extensions: {
      recommendations: [
        "dbaeumer.vscode-eslint",
        "esbenp.prettier-vscode",
      ],
    },
  };
}

export function writeVSCodeWorkspace() {
  const ws = generateVSCodeWorkspace();
  fs.writeFileSync(WORKSPACE, JSON.stringify(ws, null, 2) + "\n", "utf8");
  return WORKSPACE;
}

export function writeAll() {
  writeNginxConf();
  writeVSCodeWorkspace();
}
