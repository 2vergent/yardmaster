// Tilt orchestration helpers — invoking the `tilt` CLI and parsing its API
// for `ym status`, `ym restart`, `ym logs`. Falls back gracefully when Tilt
// isn't installed.

import fs from "fs";
import http from "http";
import path from "path";
import { spawn } from "child_process";
import {
  runInherit,
  runDetached,
  runSync,
  commandExists,
  sleep,
} from "./exec.js";
import { YM_ROOT, YM_LOCAL, TOOL_ROOT } from "./bootstrap.js";
import { byName, displayName, loadServices } from "./services.js";

const TILTFILE = path.join(TOOL_ROOT, "Tiltfile");

// Tilt's API port: services.yaml `tilt_port`, default 10350.
export const TILT_PORT = Number(loadServices().tiltPort) || 10350;
const TILT_API = `http://127.0.0.1:${TILT_PORT}`;
export const TILT_LOG = path.join(YM_LOCAL, "tilt.log");
export const TILT_PID = path.join(YM_LOCAL, "tilt.pid");
// Windows-only: the PID of the cmd that hosts the hidden window running
// the tilt.bat launcher. We need this separately from Tilt's PID because
// `taskkill /T <tilt>` walks DOWN the tree — it kills Tilt + its children
// but leaves the parent cmd window open.
export const TILT_HOST_PID = path.join(YM_LOCAL, "tilt-host.pid");
const TILT_EXE = path.join(YM_LOCAL, "bin", "tilt.exe");   // Windows only

function tiltBin() {
  if (process.platform === "win32" && fs.existsSync(TILT_EXE)) {
    return TILT_EXE;
  }
  return "tilt";
}

export function isInstalled() {
  if (process.platform === "win32" && fs.existsSync(TILT_EXE)) {
    return true;
  }
  return commandExists("tilt");
}

// up({ only, attach }) — start Tilt.
//
//   attach=true   block in the foreground, stream Tilt's TUI (the old default)
//   attach=false  detach into the background, log to .ym/tilt.log, return PID
//
// `only` restricts Tilt registration via the Tiltfile's `--only` config arg.
export async function up({ only = [], attach = false } = {}) {
  const args = ["up", "--file", TILTFILE, "--port", String(TILT_PORT)];
  if (only.length) {
    args.push("--");
    for (const name of only) {
      args.push("--only");
      args.push(name);
    }
  }

  if (attach) {
    return runInherit(tiltBin(), args, { cwd: YM_ROOT });
  }

  // Detached: fresh log per run so failures are easy to read.
  if (fs.existsSync(TILT_LOG)) fs.unlinkSync(TILT_LOG);

  let pid;
  if (process.platform === "win32") {
    pid = await startTiltWindows(args);
  } else {
    pid = await runDetached(tiltBin(), args, {
      cwd: YM_ROOT,
      logFile: TILT_LOG,
    });
  }

  if (!pid) {
    throw new Error(
      "Failed to start Tilt (no PID found). Check .ym/tilt.log for details.",
    );
  }
  // Persist the PID so `ym down` can target this exact process tree.
  fs.writeFileSync(TILT_PID, String(pid), "utf8");
  return pid;
}

// ---- Windows-specific spawn ------------------------------------------------
//
// Why this is so elaborate on Windows: if we spawn Tilt with the obvious
// `{ detached: true, windowsHide: true }`, Tilt itself runs without a
// console — but its Go runtime then spawns each local_resource child with
// CreateProcess defaults, and Windows allocates a *fresh visible console*
// for each one. With 14+ services you get dozens of windows flashing.
//
// We therefore need Tilt to have a console that is "real but never shown"
// (the SW_HIDE flag), so children inherit it cleanly. Node's spawn doesn't
// expose SW_HIDE as a distinct option — `windowsHide: true` maps to
// CREATE_NO_WINDOW, which is mutually exclusive with detached's
// DETACHED_PROCESS. The reliable native primitive that *does* let us set
// SW_HIDE explicitly is `WScript.Shell.Run(cmd, 0, False)`.
//
// So the chain is:
//   wscript.exe .ym/tilt.vbs          (wscript is a GUI app — no console)
//     └─ ws.Run "cmd /c ""<bat>""", 0, False    (SW_HIDE on the cmd)
//         └─ cmd.exe                  (hidden console)
//             └─ tilt.exe + every local_resource child (inherit hidden console)
//
// End result: no taskbar icon, no window flashing, terminal stays free —
// matching the Linux/macOS UX exactly.
//
// Both .ym/tilt.bat and .ym/tilt.vbs are regenerated on every `ym up` and
// gitignored. The .bat keeps the actual tilt invocation simple to read
// (and easy to run manually for debugging); the .vbs is just a launcher.
const TILT_BAT = path.join(YM_LOCAL, "tilt.bat");
const TILT_VBS = path.join(YM_LOCAL, "tilt.vbs");

async function startTiltWindows(args) {
  const tiltPath = tiltBin();

  // Quote any token that has whitespace in it. Service names and Tilt's
  // own flags are simple identifiers — only the absolute paths need quoting.
  const quote = (s) => (/\s/.test(s) ? `"${s}"` : s);
  const tiltArgs = args.map(quote).join(" ");

  const batContents =
    "@echo off\r\n" +
    "REM Auto-generated by ym on every `ym up`. Safe to delete.\r\n" +
    `set "YM_ROOT=${YM_ROOT}"\r\n` +
    `cd /d "${YM_ROOT}"\r\n` +
    `${quote(tiltPath)} ${tiltArgs} > ${quote(TILT_LOG)} 2>&1\r\n`;
  fs.writeFileSync(TILT_BAT, batContents, "utf8");

  // VBS string literals use doubled quote chars: "" inside a string = one
  // literal " char in the result. We want VBS to call:
  //     ws.Run "cmd /c ""<batPath>""", 0, False
  // The full VBS string literal is therefore:
  //     "cmd /c """"<bat>"""""
  //       ^               ^^^^^
  //       |               |||||
  //       |               ||||+— closing " for the VBS string
  //       |               +++--- two "" escapes → two literal " in the string
  //       +--------------------- opening " for the VBS string
  //
  // 1 open + 4 escape + 1 close on the right side = 5 quote chars after the
  // bat path. (Missing that 5th close char is what made WSH complain about
  // an unterminated string constant in an earlier revision.)
  //
  // cmd then receives:    cmd /c ""C:\path with spaces\.ym\tilt.bat""
  // cmd /c strips one outer pair, runs the bat path as a single quoted
  // token, which survives spaces in the user's home directory.
  const vbsContents =
    "' Auto-generated by ym on every `ym up`. Safe to delete.\r\n" +
    "' Hidden launcher for .ym/tilt.bat. wscript is a GUI app so it has\r\n" +
    "' no console of its own; ws.Run with windowStyle=0 (SW_HIDE) gives\r\n" +
    "' the spawned cmd a console that is never shown, so Tilt and every\r\n" +
    "' local_resource child inherit a hidden console — no taskbar icon,\r\n" +
    "' no window flashing, no second terminal anywhere on the desktop.\r\n" +
    'Set ws = CreateObject("WScript.Shell")\r\n' +
    'ws.Run "cmd /c """"' + TILT_BAT + '""""", 0, False\r\n';
  fs.writeFileSync(TILT_VBS, vbsContents, "utf8");

  // wscript.exe has no console window (it's a Windows GUI app). With
  // windowsHide: true we also suppress any borderline edge cases.
  const child = spawn(
    "wscript.exe",
    [TILT_VBS],
    {
      cwd: YM_ROOT,
      detached: true,
      stdio: "ignore",
      windowsHide: true,
    },
  );
  child.unref();

  // Tilt is two levels removed (wscript → cmd → tilt). Poll every 250ms for
  // up to 20s until it binds its API port.
  for (let i = 0; i < 80; i++) {
    await sleep(250);
    const pid = findTiltPidByPort();
    if (pid) {
      // Also record the parent cmd's PID (the one whose hidden window
      // hosts the bat). `ym down` will force-close it to dismiss the
      // hidden window — same kill mechanism as before, just on a window
      // that was never visible anyway.
      const hostPid = findParentPid(pid);
      if (hostPid) {
        fs.writeFileSync(TILT_HOST_PID, String(hostPid), "utf8");
      }
      return pid;
    }
  }
  return null;
}

function findParentPid(pid) {
  // Use PowerShell + WMI to map child PID -> parent PID. PowerShell is
  // always present on Windows 10/11; this avoids the deprecated `wmic`.
  const r = runSync("powershell", [
    "-NoProfile",
    "-Command",
    `(Get-CimInstance Win32_Process -Filter "ProcessId=${pid}").ParentProcessId`,
  ]);
  if (r.code !== 0 || !r.stdout) return null;
  const m = r.stdout.match(/(\d+)/);
  return m ? parseInt(m[1], 10) : null;
}

// PID listening on our Tilt port. Matching by port (not process name) keeps
// other projects' Tilt instances out of reach of `ym down`.
function findTiltPidByPort() {
  if (process.platform === "win32") {
    const r = runSync("netstat", ["-ano", "-p", "TCP"]);
    if (r.code !== 0 || !r.stdout) return null;
    const re = new RegExp(`:${TILT_PORT}\\s+\\S+\\s+LISTENING\\s+(\\d+)`, "i");
    const m = r.stdout.match(re);
    return m ? parseInt(m[1], 10) : null;
  }
  const r = runSync("lsof", ["-ti", `tcp:${TILT_PORT}`, "-sTCP:LISTEN"]);
  if (r.code !== 0) return null;
  const n = parseInt(r.stdout.trim().split(/\s+/)[0], 10);
  return Number.isFinite(n) ? n : null;
}

// Recovery path for `ym down` when no PID was recorded: whoever holds our
// Tilt port (callers only get here after confirming it is our Tiltfile).
function findRunningTiltPid() {
  return findTiltPidByPort();
}

// Poll Tilt's API until it responds or `timeoutMs` elapses.
export async function waitForReady(timeoutMs = 15000) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    const snap = await fetchSnapshot(800);
    if (snap) return true;
    await sleep(400);
  }
  return false;
}

// Return the last N lines of the detached tilt log (for failure reporting).
export function tailLog(lines = 30) {
  if (!fs.existsSync(TILT_LOG)) return "";
  const content = fs.readFileSync(TILT_LOG, "utf8");
  return content.split(/\r?\n/).slice(-lines).join("\n");
}

// True when a Tilt snapshot comes from this tool's Tiltfile.
function isOurSnapshot(snap) {
  const key = snap?.uiSession?.status?.tiltfileKey;
  if (!key) return ourTiltAlive();
  const norm = (p) => (process.platform === "win32" ? path.resolve(p).toLowerCase() : path.resolve(p));
  return norm(key) === norm(TILTFILE);
}

// Tiltfile path of a Tilt answering on our port that ym did not start, or null.
export async function foreignTilt() {
  const snap = (await fetchSnapshot(800)) || (await fetchSnapshot(2500));
  if (!snap || isOurSnapshot(snap)) return null;
  return snap.uiSession?.status?.tiltfileKey || "unknown Tiltfile";
}

// "Is OUR Tilt answering on the port?" — another project's Tilt on the same
// port reads as not running, so ym never stops or restarts it.
export async function isRunning() {
  // A quick probe, then a longer retry. The /api/view payload is large on big
  // stacks, so a single 500ms window false-negatives under load. This isn't a
  // latency tax on the common cases: when Tilt is DOWN the socket is refused
  // instantly (ECONNREFUSED, well under any timeout), so the slow path only
  // runs when something IS listening on :10350 but is slow to answer — exactly
  // when we want to wait long enough to confirm it's alive.
  const snap = (await fetchSnapshot(800)) || (await fetchSnapshot(2500));
  return !!snap && isOurSnapshot(snap);
}

// "Do we own a live Tilt process?" — independent of the API probe. Reads
// the PID file written by `ym up` and checks whether that PID is alive
// (signal 0 = existence test, no signal delivered). Useful when the API
// briefly doesn't answer (startup, GC, parallel-probe contention) but the
// process clearly belongs to us. PID file is overwritten on every `ym up`,
// so cross-run PID recycling is not a realistic concern.
export function ourTiltAlive() {
  const pid = readPidFile(TILT_PID);
  if (!pid) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

// Actually stop the Tilt process tree.
//
// `tilt down` only deletes K8s objects — it does NOT stop local_resource
// child processes, which is everything we use. So instead we signal the
// Tilt process directly: SIGTERM (Unix) or `taskkill /T` (Windows) to its
// process tree, then fall back to SIGKILL / `taskkill /F /T` if it's still
// alive after a grace period.
//
// Returns { stopped, reason }.
export async function down() {
  const apiAlive = await isRunning();
  let pid = readPidFile(TILT_PID);
  let hostPid = readPidFile(TILT_HOST_PID);

  // Recovery: Tilt is clearly alive but we have no recorded PID — it was
  // started outside ym, or a prior failed `ym down` deleted the PID file.
  // Find the live process by name so we can still stop it.
  if (apiAlive && !pid) {
    pid = findRunningTiltPid();
    if (pid && process.platform === "win32" && !hostPid) {
      hostPid = findParentPid(pid);
    }
  }

  if (!apiAlive && !pid && !hostPid) {
    return { stopped: false, reason: "Tilt is not running" };
  }

  // Stage 1: graceful Tilt shutdown. Walks DOWN the tree from tilt, gives
  // children a chance to exit cleanly. Does NOT touch the parent cmd window.
  if (pid) {
    await killTree(pid, /* force */ false);
  }

  // Wait up to ~5s for the API to stop responding.
  for (let i = 0; i < 20; i++) {
    if (!(await isRunning())) break;
    await sleep(250);
  }

  // Stage 2: if Tilt is still up, escalate to force-kill its tree.
  if (await isRunning()) {
    if (pid) await killTree(pid, /* force */ true);
    for (let i = 0; i < 12; i++) {
      if (!(await isRunning())) break;
      await sleep(250);
    }
  }

  // Stage 3 (Windows only): force-close the host cmd window. /F is essential
  // here because /T alone sends Ctrl+Break to cmd, which surfaces the
  // "Terminate batch job (Y/N)?" prompt and leaves the window open. /F is
  // a TerminateProcess call — immediate, no prompt, window goes away.
  if (process.platform === "win32" && hostPid) {
    await runInherit(
      "taskkill",
      ["/F", "/T", "/PID", String(hostPid)],
      { stdio: "ignore" },
    );
  }

  const stillUp = await isRunning();

  // Only clear the tracking files when we ACTUALLY stopped Tilt. Deleting them
  // after a failed kill (the old behavior) orphaned Tilt and threw away the
  // only handle to it — so the next `ym down` couldn't find it either.
  if (!stillUp) {
    for (const f of [TILT_PID, TILT_HOST_PID]) {
      try {
        if (fs.existsSync(f)) fs.unlinkSync(f);
      } catch {
        /* non-fatal */
      }
    }
  }

  return {
    stopped: !stillUp,
    reason: stillUp ? "Tilt did not exit after force-kill" : null,
  };
}

function readPidFile(p) {
  if (!fs.existsSync(p)) return null;
  const n = parseInt(fs.readFileSync(p, "utf8").trim(), 10);
  return Number.isFinite(n) ? n : null;
}

async function killTree(pid, force = false) {
  if (process.platform === "win32") {
    const args = force
      ? ["/F", "/T", "/PID", String(pid)]
      : ["/T", "/PID", String(pid)];
    // taskkill is a .exe; needsShell auto-detection in exec.js doesn't apply.
    // Use direct runInherit with stdio:ignore so its output stays silent.
    await runInherit("taskkill", args, { stdio: "ignore" });
    return;
  }

  // Unix: kill the entire process group (negative PID).
  const sig = force ? "SIGKILL" : "SIGTERM";
  try {
    process.kill(-pid, sig);
  } catch {
    // Fall back to single-process kill if the PGID isn't accessible.
    try {
      process.kill(pid, sig);
    } catch {
      /* already dead */
    }
  }
}

export function fetchSnapshot(timeoutMs = 1500) {
  return new Promise((resolve) => {
    const req = http.get(`${TILT_API}/api/view`, { timeout: timeoutMs }, (res) => {
      if (res.statusCode !== 200) {
        res.resume();
        return resolve(null);
      }
      let body = "";
      res.on("data", (c) => (body += c.toString()));
      res.on("end", () => {
        try {
          resolve(JSON.parse(body));
        } catch {
          resolve(null);
        }
      });
    });
    req.on("error", () => resolve(null));
    req.on("timeout", () => {
      req.destroy();
      resolve(null);
    });
  });
}

// Returns { name -> { status, runtimeStatus, updateStatus, lastBuildError } }.
//
// Tilt's /api/view JSON has changed shape across versions:
//   - Old (pre-0.30): { Resources: [{ Name, RuntimeStatus, ... }] }
//   - New (0.30+):    { uiResources: [{ metadata: { name }, status: { runtimeStatus, ... } }] }
// We auto-detect which shape we got. The previous code only handled the old
// shape, so on modern Tilt resourceMap() silently returned {} — that's the
// reason `ym status` was falling back to port probes ("running*") even with
// Tilt clearly running. The "Tilt API unreachable" footer in ym status
// covered the symptom; this fixes the cause.
export async function resourceMap() {
  const snap = await fetchSnapshot();
  const out = {};
  if (!snap) return out;

  // Modern shape (uiResources).
  if (Array.isArray(snap.uiResources)) {
    for (const r of snap.uiResources) {
      const name = r.metadata?.name;
      if (!name) continue;
      const st = r.status || {};
      out[name] = {
        status: st.runtimeStatus ?? st.updateStatus ?? "unknown",
        runtimeStatus: st.runtimeStatus ?? null,
        updateStatus: st.updateStatus ?? null,
        // Most-recent build's error, if any. Empty for healthy resources.
        lastBuildError: st.buildHistory?.[0]?.error ?? null,
      };
    }
    return out;
  }

  // Legacy shape (Resources). Kept for compatibility with old Tilt installs.
  if (Array.isArray(snap.Resources)) {
    for (const r of snap.Resources) {
      out[r.Name] = {
        status: r.RuntimeStatus ?? r.Status ?? "unknown",
        runtimeStatus: r.RuntimeStatus ?? null,
        updateStatus: r.UpdateStatus ?? null,
        lastBuildError: r.LastBuild?.Error ?? null,
      };
    }
  }
  return out;
}

// Tilt registers each service under its display name (services.yaml
// `display_name`); callers pass the full service name and we translate.
export function toTiltName(svcName) {
  const svc = byName(svcName);
  return svc ? displayName(svc) : svcName;
}

export async function restart(serviceName) {
  return runInherit(tiltBin(), ["trigger", "--port", String(TILT_PORT), toTiltName(serviceName)], { cwd: YM_ROOT });
}

export async function logs(serviceName, { follow = false } = {}) {
  const args = ["logs", "--port", String(TILT_PORT)];
  if (follow) args.push("-f");
  args.push(toTiltName(serviceName));
  return runInherit(tiltBin(), args, { cwd: YM_ROOT });
}

export function dashboardUrl(serviceName = null) {
  return serviceName
    ? `${TILT_API}/r/${serviceName}/overview`
    : `${TILT_API}/r/(all)/overview`;
}
